func TestLoadRejectsABadRow(t *testing.T) {
	root := t.TempDir()
	if err := os.MkdirAll(Dir(root), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(Path(root, "mini"), []byte(tsvHeader+"\n1\tIV\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := Load(root, "mini"); err == nil {
		t.Error("a row with the wrong number of columns should be an error")
	}
}

// The validator reads the map back off disk as well as building it, so what the
// volume said about where its scan begins has to survive the header.
func TestTheHeaderCarriesWhereTheScanBegins(t *testing.T) {
	root := t.TempDir()
	m, err := Build(perChapterVolume(), Options{Book: "mini", Chapters: []string{"IV"}, FirstPage: 3})
	if err != nil {
		t.Fatal(err)
	}
	if err := m.Save(root); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(Path(root, "mini"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(b), "first_page=3") {
		t.Errorf("the header does not say where the scan begins:\n%s", strings.SplitN(string(b), "\n", 3)[1])
	}
	back, err := Load(root, "mini")
	if err != nil {
		t.Fatal(err)
	}
	if back.FirstPage != 3 {
		t.Errorf("first page came back as %d, want 3", back.FirstPage)
	}
	// A volume whose scan starts at the beginning writes nothing.
	plain, err := Build(perChapterVolume(), Options{Book: "plain", Chapters: []string{"IV"}})
	if err != nil {
		t.Fatal(err)
	}
	if err := plain.Save(root); err != nil {
		t.Fatal(err)
	}
	b, err = os.ReadFile(Path(root, "plain"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(b), "first_page") {
		t.Error("a scan that starts at the beginning wrote a first page anyway")
	}
}

// The restarts have to survive the round trip for the same reason the first
// page does: Validate runs against a map loaded from disk, and without them the
// one place the numbering is allowed to go backwards reads as the fit slipping.
func TestTheHeaderCarriesWhereTheNumberingStartsOver(t *testing.T) {
	root := t.TempDir()
	m, err := Build(perChapterVolume(), Options{Book: "mini", Chapters: []string{"IV"},
		Restarts: []int{3, 5}})
	if err != nil {
		t.Fatal(err)
	}
	if err := m.Save(root); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(Path(root, "mini"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(b), "restarts=3,5") {
		t.Errorf("the header does not say where the numbering starts over:\n%s",
			strings.SplitN(string(b), "\n", 3)[1])
	}
	back, err := Load(root, "mini")
	if err != nil {
		t.Fatal(err)
	}
	if len(back.Restarts) != 2 || back.Restarts[0] != 3 || back.Restarts[1] != 5 {
		t.Errorf("the restarts came back as %v, want [3 5]", back.Restarts)
	}
	// A volume that numbers itself once through writes nothing.
	plain, err := Build(perChapterVolume(), Options{Book: "plain", Chapters: []string{"IV"}})
	if err != nil {
		t.Fatal(err)
	}
	if err := plain.Save(root); err != nil {
		t.Fatal(err)
	}
	b, err = os.ReadFile(Path(root, "plain"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(b), "restarts") {
		t.Error("a volume numbered once through wrote a restart anyway")
	}
}
